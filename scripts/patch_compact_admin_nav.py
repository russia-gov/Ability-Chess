#!/usr/bin/env python3
"""Put member-management controls in the Admin page's actual HTML.

Do not depend on a deferred account callback to create the directory controls.
Avoid touching account/session initialization or the game UI.
"""
from pathlib import Path
import sys

path=Path(sys.argv[1] if len(sys.argv)>1 else "index.html")
s=path.read_text(encoding="utf-8")
marker="ABILITY_CHESS_ADMIN_MANAGEMENT_STATIC_V2"
if marker in s:
    print("Admin management controls already installed")
    raise SystemExit(0)

anchor="  const originalUpdateSidebarAccounts=updateSidebarAccounts;"
if s.count(anchor)!=1:
    raise SystemExit("Unexpected sidebar structure; not modifying page")

# Remove the older nav wrappers, whether generated by previous builds or
# freshly inserted by the build before this script runs.
for prefix in (
    "  // ABILITY_CHESS_ADMIN_DIRECTORY_NAV_V1",
    "  // ABILITY_CHESS_DM_SAFETY_NAV_V1",
    "  // ABILITY_CHESS_COMPACT_ADMIN_NAV_V1",
):
    if prefix in s:
        start=s.index(prefix)
        end=s.index(anchor,start)
        s=s[:start]+s[end:]

# A previous build may have installed the dynamic card. It no longer needs to
# be called: the Admin controls are present in HTML from first paint.
s=s.replace(
    "ensureAdminFoundationCards();loadModerationFoundation();ensureCompactAdminTools();}",
    "ensureAdminFoundationCards();loadModerationFoundation();}",
)

# Insert directly into the actual Admin screen, immediately before the
# existing management grid. This works even if Admin loading is asynchronous.
admin_start=s.find('<div id="adminScreen"')
if admin_start<0:
    raise SystemExit("Admin screen not found")
grid_start=s.find('<div class="admin-grid">',admin_start)
if grid_start<0 or grid_start-admin_start>10000:
    raise SystemExit("Admin grid not found near the Admin screen")
if 'id="adminManagementPanel"' not in s:
    panel='''<section id="adminManagementPanel" class="admin-card" style="margin:18px 0">
      <h2>Member management</h2>
      <p class="history-meta">Manage member accounts and review reported private messages.</p>
      <div class="history-actions">
        <button type="button" data-admin-management="directory">Member directory</button>
        <button type="button" data-admin-management="reports">DM reports</button>
        <button type="button" id="adminManagementClose" hidden>Close</button>
      </div>
      <iframe id="adminManagementFrame" title="Admin management" loading="lazy"
        style="display:none;width:100%;height:min(75vh,850px);min-height:540px;margin-top:12px;border:1px solid #465363;border-radius:10px;background:#11171d"></iframe>
    </section>'''
    s=s[:grid_start]+panel+s[grid_start:]

# Using a single delegated listener makes this resilient to sidebar redraws
# and does not touch the existing member login flow.
listener='''  // ABILITY_CHESS_ADMIN_MANAGEMENT_STATIC_V2
  document.addEventListener('click',event=>{
    const select=event.target.closest?.('[data-admin-management]');
    const close=event.target.closest?.('#adminManagementClose');
    if(!select&&!close)return;
    const panel=document.getElementById('adminManagementPanel');
    const frame=panel?.querySelector('#adminManagementFrame');
    const closeButton=panel?.querySelector('#adminManagementClose');
    if(!frame||!closeButton)return;
    if(close){
      frame.removeAttribute('src');
      frame.style.display='none';
      closeButton.hidden=true;
      return;
    }
    const kind=select.getAttribute('data-admin-management');
    if(kind!=='directory'&&kind!=='reports')return;
    frame.src=kind==='directory'
      ? 'admin-directory.html?embedded=1'
      : 'dm-safety.html?embedded=1#reports';
    frame.title=kind==='directory'?'Member directory':'Reported direct messages';
    frame.style.display='block';
    closeButton.hidden=false;
  });
'''
s=s.replace(anchor,listener+anchor,1)
path.write_text(s,encoding="utf-8")
print("Admin directory and DM reports are now static controls inside Admin")
